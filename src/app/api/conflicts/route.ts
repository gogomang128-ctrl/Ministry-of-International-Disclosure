export async function GET() {
  const rows = await db.select().from(conflicts);

  // live pulse: pick a random conflict and stamp a fresh development
  const active = rows.filter((r) => r.intensity !== "ceasefire");
  const pool = active.length ? active : rows;
  let updated = rows[0];
  if (pool.length) {
    const pick = pool[Math.floor(Math.random() * pool.length)];
    const devs = DEVELOPMENT_POOL[pick.code] ?? [];
    const dev = devs.length ? devs[Math.floor(Math.random() * devs.length)] : pick.latest;
    [updated] = await db
      .update(conflicts)
      .set({ latest: dev, updatedAt: new Date() })
      .where(eq(conflicts.id, pick.id))
      .returning();
  }

  const list = rows
    .map((r) => (r.id === updated.id ? updated : r))
    .sort((a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime());

  return NextResponse.json({
    ok: true,
    generatedAt: new Date().toISOString(),
    conflicts: list,
  });
}
