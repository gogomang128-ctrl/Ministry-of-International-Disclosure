export async function GET() {
  const rows = await db.select().from(wars);
  if (!rows.length) {
    return NextResponse.json({ ok: true, generatedAt: new Date().toISOString(), wars: [] });
  }

  // live pulse: stamp a fresh development on one random war
  const pick = rows[Math.floor(Math.random() * rows.length)];
  const devs = DEVELOPMENT_POOL[pick.code] ?? FALLBACK[pick.intensity] ?? FALLBACK.tension;
  const dev = devs[Math.floor(Math.random() * devs.length)];
  const [updated] = await db
    .update(wars)
    .set({ latest: dev, updatedAt: new Date() })
    .where(eq(wars.id, pick.id))
    .returning();

  const list = rows
    .map((r) => (r.id === updated.id ? updated : r))
    .sort((a, b) => new Date(b.updatedAt).getTime() - new Date(a.updatedAt).getTime());

  return NextResponse.json({
    ok: true,
    generatedAt: new Date().toISOString(),
    wars: list,
  });
}
